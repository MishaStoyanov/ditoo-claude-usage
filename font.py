"""4-pixel-tall letters for account labels. Each glyph is centered in a 5px-wide column."""

GLYPHS = {
    "A": ["010", "101", "111", "101"],
    "B": ["110", "111", "101", "110"],
    "C": ["011", "100", "100", "011"],
    "D": ["110", "101", "101", "110"],
    "E": ["111", "110", "100", "111"],
    "F": ["111", "100", "110", "100"],
    "G": ["011", "100", "101", "011"],
    "H": ["101", "111", "101", "101"],
    "I": ["111", "010", "010", "111"],
    "J": ["001", "001", "101", "010"],
    "K": ["101", "110", "110", "101"],
    "L": ["100", "100", "100", "111"],
    "M": ["10001", "11011", "10101", "10001"],
    "N": ["1001", "1101", "1011", "1001"],
    "O": ["010", "101", "101", "010"],
    "P": ["110", "101", "110", "100"],
    "Q": ["0110", "1001", "1011", "0111"],
    "R": ["110", "101", "110", "101"],
    "S": ["0111", "1100", "0011", "1110"],
    "T": ["111", "010", "010", "010"],
    "U": ["101", "101", "101", "111"],
    "V": ["101", "101", "101", "010"],
    "W": ["10001", "10101", "10101", "01010"],
    "X": ["101", "010", "010", "101"],
    "Y": ["101", "101", "010", "010"],
    "Z": ["1111", "0010", "0100", "1111"],
}

LABEL_WIDTH = 5


def glyph_pixels(letter):
    """Yields (x, y) of lit pixels, x already offset to center the glyph in the label column."""
    rows = GLYPHS[letter.upper()]
    x0 = (LABEL_WIDTH - len(rows[0])) // 2
    for y, row in enumerate(rows):
        for x, bit in enumerate(row):
            if bit == "1":
                yield x0 + x, y
